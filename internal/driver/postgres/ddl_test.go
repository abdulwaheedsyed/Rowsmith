func strp(s string) *string { return &s }

func TestPGAlterTableSQL(t *testing.T) {
	c := &conn{}
	from := &driver.Table{
		Ref: driver.ObjectRef{Schema: "app", Name: "items"},
		Columns: []driver.Column{
			{Name: "id", Type: "integer", Default: strp("GENERATED BY DEFAULT AS IDENTITY")},
			{Name: "price", Type: "numeric(10,2)", Nullable: true, Default: strp("0")},
			{Name: "legacy", Type: "text", Nullable: true},
		},
		PrimaryKey: []string{"id"},
		Indexes:    []driver.Index{{Name: "items_pkey", Primary: true, Unique: true, Columns: []string{"id"}}},
	}
	to := driver.TableDef{
		Ref: driver.ObjectRef{Schema: "app", Name: "items"},
		Columns: []driver.ColumnDef{
			{Column: driver.Column{Name: "id", Type: "integer", Default: strp("GENERATED BY DEFAULT AS IDENTITY")}, OriginalName: "id"},
			{Column: driver.Column{Name: "amount", Type: "numeric(12,2)", Comment: "in cents"}, OriginalName: "price"},
			{Column: driver.Column{Name: "tags", Type: "text[]", Nullable: true, Default: strp("'{}'")}},
		},
		PrimaryKey: []string{"id"},
		Indexes:    []driver.Index{{Name: "items_tags", Columns: []string{"tags"}, Type: "gin"}},
	}
	stmts, err := c.AlterTableSQL(from, to)
	if err != nil {
		t.Fatal(err)
	}
	joined := strings.Join(stmts, "\n")
	for _, want := range []string{
		`ALTER TABLE "app"."items" DROP COLUMN "legacy"`,
		`ALTER TABLE "app"."items" RENAME COLUMN "price" TO "amount"`,
		`ALTER TABLE "app"."items" ALTER COLUMN "amount" TYPE numeric(12,2) USING "amount"::numeric(12,2)`,
		`ALTER TABLE "app"."items" ALTER COLUMN "amount" SET NOT NULL`,
		`ALTER TABLE "app"."items" ALTER COLUMN "amount" DROP DEFAULT`,
		`COMMENT ON COLUMN "app"."items"."amount" IS 'in cents'`,
		`ALTER TABLE "app"."items" ADD COLUMN "tags" text[] DEFAULT '{}'`,
		`CREATE INDEX "items_tags" ON "app"."items" USING gin ("tags")`,
	} {
		if !strings.Contains(joined, want) {
			t.Errorf("missing %q in:\n%s", want, joined)
		}
	}
	if strings.Contains(joined, "items_pkey") || strings.Contains(joined, `"id"`) && strings.Contains(joined, `ALTER COLUMN "id"`) {
		t.Errorf("unchanged key touched:\n%s", joined)
	}
}

func TestPGAutoIncrementBecomesIdentity(t *testing.T) {
	c := &conn{}
	stmts, err := c.CreateTableSQL(driver.TableDef{
		Ref:        driver.ObjectRef{Schema: "app", Name: "t"},
		Columns:    []driver.ColumnDef{{Column: driver.Column{Name: "id", Type: "bigint", AutoIncrement: true}}},
		PrimaryKey: []string{"id"},
	})
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(stmts[0], `"id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL`) {
		t.Errorf("got %s", stmts[0])
	}
}

func TestPGRenameKeepsIndexes(t *testing.T) {
	c := &conn{}
	from := &driver.Table{
		Ref:        driver.ObjectRef{Schema: "public", Name: "t"},
		Columns:    []driver.Column{{Name: "id", Type: "bigint"}, {Name: "title", Type: "text"}},
		PrimaryKey: []string{"id"},
		Indexes:    []driver.Index{{Name: "t_title", Columns: []string{"title"}, Unique: true, Type: "btree"}},
	}
	for _, idxCol := range []string{"headline", "title"} { // editors may send the new or the old name
		to := driver.TableDef{
			Ref: from.Ref,
			Columns: []driver.ColumnDef{
				{Column: driver.Column{Name: "id", Type: "bigint"}, OriginalName: "id"},
				{Column: driver.Column{Name: "headline", Type: "text"}, OriginalName: "title"},
			},
			PrimaryKey: []string{"id"},
			Indexes:    []driver.Index{{Name: "t_title", Columns: []string{idxCol}, Unique: true, Type: "btree"}},
		}
		stmts, err := c.AlterTableSQL(from, to)
		if err != nil {
			t.Fatal(err)
		}
		if len(stmts) != 1 || !strings.Contains(stmts[0], `RENAME COLUMN "title" TO "headline"`) {
			t.Errorf("index %s: got %q", idxCol, stmts)
		}
	}
}

func TestPGDropDatabase(t *testing.T) {
	c := &conn{pools: map[string]*pool{}}
	got, err := c.DropDatabaseSQL("Sales", false)
	if err != nil || strings.Join(got, ";") != `DROP DATABASE "Sales"` {
		t.Fatalf("plain: %v %v", got, err)
	}
	got, err = c.DropDatabaseSQL("Sales", true)
	if err != nil || strings.Join(got, ";") != `DROP DATABASE "Sales" WITH (FORCE)` {
		t.Fatalf("force: %v %v", got, err)
	}
	c.pools[""] = &pool{server: 120011}
	if _, err := c.DropDatabaseSQL("Sales", true); err == nil {
		t.Fatal("WITH (FORCE) accepted on PostgreSQL 12")
	}
}

// TestPGDroppedDatabase: the session releases its own pool for the database a
// statement drops, so it must read the name as PostgreSQL does.
func TestPGDroppedDatabase(t *testing.T) {
	for stmt, want := range map[string]string{
		`DROP DATABASE shop`:                   "shop",
		"  drop database IF EXISTS Shop;":      "shop",
		`DROP DATABASE "Shop"`:                 "Shop",
		`DROP DATABASE "we""ird" WITH (FORCE)`: `we"ird`,
		"DROP\n DATABASE\tcafé":                "café",
	} {
		if got, ok := droppedDatabase(stmt); !ok || got != want {
			t.Errorf("%q: got %q, %v; want %q", stmt, got, ok, want)
		}
	}
	for _, stmt := range []string{`DROP TABLE shop`, `SELECT 'DROP DATABASE shop'`, `DROP DATABASES shop`} {
		if got, ok := droppedDatabase(stmt); ok {
			t.Errorf("%q read as dropping %q", stmt, got)
		}
	}
}

