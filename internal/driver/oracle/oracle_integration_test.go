// The integration test needs a server, e.g. the dev container:
//
//	ROWSMITH_TEST_ORACLE_HOST=oracle ROWSMITH_TEST_ORACLE_PASSWORD=... go test -run Integration ./internal/driver/oracle/
//
// Optional: ROWSMITH_TEST_ORACLE_PORT, ROWSMITH_TEST_ORACLE_SERVICE (FREEPDB1),
// ROWSMITH_TEST_ORACLE_USER (shop) and ROWSMITH_TEST_ORACLE_SYSTEM_PASSWORD
// (defaults to the password; SYSTEM checks are skipped when it fails).

func testParams(t *testing.T, user, password string) driver.OpenParams {
	host := os.Getenv("ROWSMITH_TEST_ORACLE_HOST")
	if host == "" {
		t.Skip("set ROWSMITH_TEST_ORACLE_HOST to run Oracle integration tests")
	}
	service := os.Getenv("ROWSMITH_TEST_ORACLE_SERVICE")
	if service == "" {
		service = "FREEPDB1"
	}
	params := map[string]any{"host": host, "service": service, "user": user, "connectTimeout": 20}
	if port := os.Getenv("ROWSMITH_TEST_ORACLE_PORT"); port != "" {
		params["port"] = port
	}
	return driver.OpenParams{Params: params, Secrets: map[string]string{"password": password}, AppName: "rowsmith-test"}
}

func appUser() string {
	if u := os.Getenv("ROWSMITH_TEST_ORACLE_USER"); u != "" {
		return u
	}
	return "shop"
}

func systemPassword() string {
	if p := os.Getenv("ROWSMITH_TEST_ORACLE_SYSTEM_PASSWORD"); p != "" {
		return p
	}
	return os.Getenv("ROWSMITH_TEST_ORACLE_PASSWORD")
}

func mustOpen(t *testing.T, p driver.OpenParams) *conn {
	t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), time.Minute)
	defer cancel()
	c, err := oracleDriver{}.Open(ctx, p)
	if err != nil {
		t.Fatalf("open: %v", err)
	}
	t.Cleanup(func() { c.Close() })
	return c.(*conn)
}

