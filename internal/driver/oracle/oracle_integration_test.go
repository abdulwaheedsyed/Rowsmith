	t.Run("Session", func(t *testing.T) {
		sess, err := c.NewSession(ctx, driver.Scope{})
		if err != nil {
			t.Fatal(err)
		}
		defer sess.Close()
		script := `CREATE TABLE RS_TMP (ID NUMBER PRIMARY KEY, V VARCHAR2(20), DOC CLOB);
INSERT INTO RS_TMP (ID, V) VALUES (1, 'a');
BEGIN
  INSERT INTO RS_TMP (ID, V) VALUES (2, 'b');
  DBMS_OUTPUT.PUT_LINE('inserted two');
  RS_GREET('world');
END;
/
SELECT ID, V, DOC, CAST(1.5 AS NUMBER(5,2)) AS X, SYSDATE AS D FROM RS_TMP ORDER BY ID;
EXEC RS_GREET('exec')`
		out := run(t, sess, script, driver.ExecOptions{MaxRows: 100, StopOnError: true})
		if len(out.stmts) != 5 {
			t.Fatalf("statements %d", len(out.stmts))
		}
		for _, st := range out.stmts {
			if st.err != nil {
				t.Fatalf("statement %q: %v", st.info.SQL, st.err)
			}
		}
		if n := out.stmts[2].notices; len(n) != 2 || n[0] != "output: inserted two" || n[1] != "output: Hello, world" {
			t.Errorf("block notices %q", n)
		}
		if out.stmts[2].info.Line != 3 {
			t.Errorf("block line %d", out.stmts[2].info.Line)
		}
		sel := out.stmts[3]
		if len(sel.rows) != 2 || len(sel.cols) != 1 || sel.cols[0][2].Type != "CLOB" || sel.cols[0][1].Type != "VARCHAR2" || sel.rows[0][3] != "1.5" {
			t.Errorf("select cols %+v rows %v", sel.cols, sel.rows)
		}
		if n := out.stmts[4].notices; len(n) != 1 || n[0] != "output: Hello, exec" {
			t.Errorf("exec notices %q", n)
		}
		if !sess.InTransaction() {
			t.Error("inserts should leave a transaction open")
		}
		// The second run sees the uncommitted rows; other connections do not.
		out = run(t, sess, "SELECT COUNT(*) FROM RS_TMP", driver.ExecOptions{})
		if out.stmts[0].err != nil || out.stmts[0].rows[0][0] != "2" {
			t.Errorf("same session count %v %v", out.stmts[0].rows, out.stmts[0].err)
		}
		if n, err := c.Count(ctx, driver.BrowseRequest{Ref: driver.ObjectRef{Name: "RS_TMP"}}); err != nil || n.Rows != 0 {
			t.Errorf("other connection sees %+v %v", n, err)
		}
		out = run(t, sess, "ROLLBACK;\nSELECT COUNT(*) FROM RS_TMP", driver.ExecOptions{})
		if out.stmts[1].rows[0][0] != "0" || sess.InTransaction() {
			t.Errorf("after rollback %v in tx %v", out.stmts[1].rows, sess.InTransaction())
		}

		// Errors point at the right script line.
		out = run(t, sess, "SELECT 1 FROM DUAL;\nBEGIN\n  NULL;\n  undefined_x := 1;\nEND;\n/", driver.ExecOptions{})
		if qe := queryErr(t, out.stmts[1].err); qe.Line != 4 || qe.Code != "ORA-06550" || !strings.HasPrefix(qe.Message, "PLS-00201") {
			t.Errorf("PL/SQL compile error %+v", qe)
		}
		out = run(t, sess, "\nBEGIN\n  RAISE_APPLICATION_ERROR(-20001, 'boom');\nEND;", driver.ExecOptions{})
		if qe := queryErr(t, out.stmts[0].err); qe.Line != 3 || qe.Code != "ORA-20001" || qe.Message != "ORA-20001: boom" {
			t.Errorf("runtime error %+v", qe)
		}
		out = run(t, sess, "SELECT 1 FROM DUAL;\nSELECT *\n  FROM RS_NO_SUCH_TABLE", driver.ExecOptions{})
		if qe := queryErr(t, out.stmts[1].err); qe.Line != 3 || qe.Code != "ORA-00942" || qe.Position == 0 || strings.Contains(qe.Message, "error occur") {
			t.Errorf("SQL error %+v", qe)
		}
		out = run(t, sess, "CREATE OR REPLACE PROCEDURE RS_BAD IS\nBEGIN\n  undefined_y := 1;\nEND;\n/\nSELECT 1 FROM DUAL", driver.ExecOptions{})
		if qe := queryErr(t, out.stmts[0].err); qe.Line != 3 || qe.Code != "PLS-00201" || !strings.Contains(qe.Detail, "compilation errors") {
			t.Errorf("compilation error %+v", qe)
		}
		if out.stmts[1].err != nil {
			t.Errorf("statement after a compilation error: %v", out.stmts[1].err)
		}

		// A result go-ora cannot decode resets the console instead of breaking it.
		out = run(t, sess, "SELECT PT FROM RS_SHAPES", driver.ExecOptions{})
		if !errors.Is(out.stmts[0].err, errDriverFailure) {
			t.Errorf("object column: %v", out.stmts[0].err)
		}
		out = run(t, sess, "SELECT 'ok' FROM DUAL", driver.ExecOptions{})
		if out.stmts[0].err != nil || out.stmts[0].rows[0][0] != "ok" {
			t.Errorf("after reconnect: %v %v", out.stmts[0].rows, out.stmts[0].err)
		}

		// A cancelled statement leaves the console usable.
		cctx, cancel := context.WithTimeout(ctx, 500*time.Millisecond)
		cs := &recSink{}
		_ = sess.Execute(cctx, "SELECT COUNT(*) FROM ALL_OBJECTS a, ALL_OBJECTS b, ALL_OBJECTS c", driver.ExecOptions{}, cs)
		cancel()
		if len(cs.stmts) != 1 || cs.stmts[0].err == nil {
			t.Fatalf("cancelled statement: %+v", cs.stmts)
		}
		out = run(t, sess, "SELECT 'still ok' FROM DUAL", driver.ExecOptions{})
		if out.stmts[0].err != nil || out.stmts[0].rows[0][0] != "still ok" {
			t.Errorf("after cancel: %v %v", out.stmts[0].rows, out.stmts[0].err)
		}

		// Read-only runs are enforced by the classifier.
		out = run(t, sess, "INSERT INTO RS_LOG (MSG) VALUES ('x');\nSELECT 1 FROM DUAL", driver.ExecOptions{ReadOnly: true})
		if out.stmts[0].err == nil || out.stmts[1].err != nil {
			t.Errorf("read-only: %v / %v", out.stmts[0].err, out.stmts[1].err)
		}
	})

