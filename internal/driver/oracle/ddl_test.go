// Oracle refuses some column changes under indexes and virtual columns;
// the indexes are rebuilt around the change, the rest is refused up front.
func TestAlterDependencies(t *testing.T) {
	tbl := describedCustomers()
	tbl.Indexes = append(tbl.Indexes, driver.Index{Name: "RS_CUSTOMERS_NU_IX", Columns: []string{"NAME_UPPER"}, Type: "btree", Desc: []bool{false}})

	// Retyping EMAIL rebuilds the function-based index on LOWER("EMAIL"),
	// under the column's new name.
	def := tableDef(tbl)
	email := defColumn(&def, "EMAIL")
	email.Name, email.Type = "MAIL", "VARCHAR2(320 BYTE)"
	wantStatements(t, alterSQL(t, tbl, def), []string{
		`DROP INDEX "SHOP"."RS_CUSTOMERS_LOWER_IX"`,
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" RENAME COLUMN "EMAIL" TO "MAIL"`,
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" MODIFY ("MAIL" VARCHAR2(320 BYTE))`,
		`CREATE INDEX "SHOP"."RS_CUSTOMERS_LOWER_IX" ON "SHOP"."RS_CUSTOMERS" (LOWER("MAIL"))`,
	})

	// A new virtual expression rebuilds the indexes on that column.
	def = tableDef(tbl)
	defColumn(&def, "NAME_UPPER").Generated = `LOWER("NAME")`
	wantStatements(t, alterSQL(t, tbl, def), []string{
		`DROP INDEX "SHOP"."RS_CUSTOMERS_NU_IX"`,
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" MODIFY ("NAME_UPPER" AS (LOWER("NAME")))`,
		`CREATE INDEX "SHOP"."RS_CUSTOMERS_NU_IX" ON "SHOP"."RS_CUSTOMERS" ("NAME_UPPER")`,
	})

	// Renaming NAME alone changes nothing else: Oracle updates the virtual
	// column and the check that use it. Changed ones are written with the
	// new name even when the definition still has the old one.
	tbl.Checks = append(tbl.Checks, driver.Check{Name: "RS_CUSTOMERS_NAME_CK", Expression: `"NAME" <> '"NAME"'`})
	def = tableDef(tbl)
	defColumn(&def, "NAME").Name = "FULL_NAME"
	wantStatements(t, alterSQL(t, tbl, def), []string{`ALTER TABLE "SHOP"."RS_CUSTOMERS" RENAME COLUMN "NAME" TO "FULL_NAME"`})
	defColumn(&def, "NAME_UPPER").Type = "VARCHAR2(500 CHAR)"
	def.Checks[2].Expression = `"NAME" NOT IN ('"NAME"', 'x')`
	wantStatements(t, alterSQL(t, tbl, def), []string{
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" DROP CONSTRAINT "RS_CUSTOMERS_NAME_CK"`,
		`DROP INDEX "SHOP"."RS_CUSTOMERS_NU_IX"`,
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" RENAME COLUMN "NAME" TO "FULL_NAME"`,
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" MODIFY ("NAME_UPPER" VARCHAR2(500 CHAR) AS (UPPER("FULL_NAME")))`,
		`CREATE INDEX "SHOP"."RS_CUSTOMERS_NU_IX" ON "SHOP"."RS_CUSTOMERS" ("NAME_UPPER")`,
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" ADD CONSTRAINT "RS_CUSTOMERS_NAME_CK" CHECK ("FULL_NAME" NOT IN ('"NAME"', 'x'))`,
	})

	// NAME cannot be retyped while NAME_UPPER uses it, unless it goes.
	def = tableDef(tbl)
	defColumn(&def, "NAME").Type = "VARCHAR2(200 CHAR)"
	if _, err := testConn().AlterTableSQL(tbl, def); err == nil ||
		err.Error() != "column NAME is used by virtual column NAME_UPPER, so Oracle cannot change its type; drop NAME_UPPER first" {
		t.Errorf("retyping a column a virtual column uses: %v", err)
	}
	var cols []driver.ColumnDef
	for _, col := range def.Columns {
		if col.Name != "NAME_UPPER" {
			cols = append(cols, col)
		}
	}
	def.Columns = cols
	def.Indexes = def.Indexes[:len(def.Indexes)-1]
	wantStatements(t, alterSQL(t, tbl, def), []string{
		`DROP INDEX "SHOP"."RS_CUSTOMERS_NU_IX"`,
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" DROP COLUMN "NAME_UPPER"`,
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" MODIFY ("NAME" VARCHAR2(200 CHAR))`,
	})
}

func TestAlterSelfReference(t *testing.T) {
	self := driver.ObjectRef{Schema: "SHOP", Name: "EMP", Kind: "table"}
	fk := driver.ForeignKey{Name: "EMP_MANAGER_FK", Columns: []string{"MANAGER_ID"}, RefTable: self, RefColumns: []string{"ID"}, OnDelete: "SET NULL", Table: &self}
	emp := &driver.Table{Ref: self, Kind: "table",
		Columns:     []driver.Column{{Name: "ID", Type: "NUMBER"}, {Name: "MANAGER_ID", Type: "NUMBER", Nullable: true}},
		PrimaryKey:  []string{"ID"},
		Indexes:     []driver.Index{{Name: "EMP_PK", Columns: []string{"ID"}, Unique: true, Primary: true}},
		ForeignKeys: []driver.ForeignKey{fk}, Referenced: []driver.ForeignKey{fk},
	}
	for _, follow := range []bool{false, true} {
		def := tableDef(emp)
		def.Columns[0].Name, def.Ref.Name = "EMP_ID", "STAFF"
		if follow {
			def.PrimaryKey, def.ForeignKeys[0].RefColumns, def.ForeignKeys[0].RefTable.Name = []string{"EMP_ID"}, []string{"EMP_ID"}, "STAFF"
		}
		wantStatements(t, alterSQL(t, emp, def), []string{
			`ALTER TABLE "SHOP"."EMP" RENAME COLUMN "ID" TO "EMP_ID"`,
			`ALTER TABLE "SHOP"."EMP" RENAME TO "STAFF"`,
		})
	}
	// Its own foreign key does not stop the key from changing when it goes too.
	def := tableDef(emp)
	def.PrimaryKey, def.ForeignKeys = []string{"ID", "MANAGER_ID"}, nil
	wantStatements(t, alterSQL(t, emp, def), []string{
		`ALTER TABLE "SHOP"."EMP" DROP CONSTRAINT "EMP_MANAGER_FK"`,
		`ALTER TABLE "SHOP"."EMP" DROP PRIMARY KEY DROP INDEX`,
		`ALTER TABLE "SHOP"."EMP" ADD CONSTRAINT "EMP_PK" PRIMARY KEY ("ID", "MANAGER_ID")`,
	})
	def.ForeignKeys = tableDef(emp).ForeignKeys
	if _, err := testConn().AlterTableSQL(emp, def); err == nil ||
		err.Error() != "the primary key is referenced by foreign key EMP.EMP_MANAGER_FK; drop that foreign key first" {
		t.Errorf("kept self reference: %v", err)
	}

	// A referenced column cannot be dropped either.
	tbl := describedCustomers()
	tbl.Referenced = append(tbl.Referenced, driver.ForeignKey{Name: "RS_LOGINS_EMAIL_FK", RefColumns: []string{"EMAIL"}, Table: &driver.ObjectRef{Schema: "SHOP", Name: "RS_LOGINS"}})
	def = tableDef(tbl)
	def.Columns = append(def.Columns[:2], def.Columns[3:]...)
	if _, err := testConn().AlterTableSQL(tbl, def); err == nil ||
		err.Error() != "column EMAIL is referenced by foreign key RS_LOGINS.RS_LOGINS_EMAIL_FK; drop that foreign key first" {
		t.Errorf("referenced column: %v", err)
	}
	def.Indexes = def.Indexes[:1]
	if _, err := testConn().AlterTableSQL(tbl, def); err == nil || !strings.HasPrefix(err.Error(), "unique key RS_CUSTOMERS_EMAIL_UK is referenced") {
		t.Errorf("referenced unique key: %v", err)
	}
}
