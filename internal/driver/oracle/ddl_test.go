func TestAlterColumns(t *testing.T) {
	tbl := describedCustomers()
	def := tableDef(tbl)
	def.Columns[1].Name = "FULL_NAME"                                          // NAME renamed
	def.Columns[2].Type, def.Columns[2].Nullable = "VARCHAR2(320 BYTE)", false // EMAIL widened, required
	def.Columns[2].Comment = ""
	def.Columns[3].Default = nil                                             // CREATED loses its default
	def.Columns[4].Default, def.Columns[4].Comment = strp("100"), "In cents" // BALANCE
	def.Columns[6].Generated = `LOWER("FULL_NAME")`                          // NAME_UPPER
	def.Columns = append(def.Columns[:5], def.Columns[6:]...)                // STATUS dropped
	def.Columns = append(def.Columns, driver.ColumnDef{Column: driver.Column{Name: "TAGS", Type: "VARCHAR2(200 CHAR)", Nullable: true, Default: strp("'none'"), Comment: "Labels"}})
	def.Comment = ""
	def.Ref.Name = "RS_CLIENTS"
	wantStatements(t, alterSQL(t, tbl, def), []string{
		`DROP INDEX "SHOP"."RS_CUSTOMERS_LOWER_IX"`, // on LOWER("EMAIL"), which changes type
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" DROP COLUMN "STATUS"`,
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" RENAME COLUMN "NAME" TO "FULL_NAME"`,
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" MODIFY ("EMAIL" VARCHAR2(320 BYTE) NOT NULL)`,
		`COMMENT ON COLUMN "SHOP"."RS_CUSTOMERS"."EMAIL" IS ''`,
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" MODIFY ("CREATED" DEFAULT NULL)`,
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" MODIFY ("BALANCE" DEFAULT 100)`,
		`COMMENT ON COLUMN "SHOP"."RS_CUSTOMERS"."BALANCE" IS 'In cents'`,
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" MODIFY ("NAME_UPPER" AS (LOWER("FULL_NAME")))`,
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" ADD ("TAGS" VARCHAR2(200 CHAR) DEFAULT 'none')`,
		`COMMENT ON COLUMN "SHOP"."RS_CUSTOMERS"."TAGS" IS 'Labels'`,
		`CREATE INDEX "SHOP"."RS_CUSTOMERS_LOWER_IX" ON "SHOP"."RS_CUSTOMERS" (LOWER("EMAIL"))`,
		`COMMENT ON TABLE "SHOP"."RS_CUSTOMERS" IS ''`,
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" RENAME TO "RS_CLIENTS"`,
	})

	// Nullability is only sent when it changes; NULL on its own too.
	def = tableDef(tbl)
	def.Columns[1].Nullable = true
	def.Columns[6].Type, def.Columns[6].Nullable = "VARCHAR2(500 CHAR)", false
	wantStatements(t, alterSQL(t, tbl, def), []string{
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" MODIFY ("NAME" NULL)`,
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" MODIFY ("NAME_UPPER" VARCHAR2(500 CHAR) AS (UPPER("NAME")))`,
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" MODIFY ("NAME_UPPER" NOT NULL)`,
	})
}

func TestAlterDefaultOnNull(t *testing.T) {
	tbl := describedCustomers() // STATUS: DEFAULT ON NULL 'new', NOT NULL
	cases := []struct {
		def      *string
		nullable bool
		want     []string
	}{
		{strp("ON NULL 'open'"), false, []string{`MODIFY ("STATUS" DEFAULT ON NULL 'open')`}},
		// Leaving ON NULL drops its NOT NULL, which has to be restored.
		{strp("'open'"), false, []string{`MODIFY ("STATUS" DEFAULT 'open')`, `MODIFY ("STATUS" NOT NULL)`}},
		{nil, true, []string{`MODIFY ("STATUS" DEFAULT NULL)`}},
	}
	for _, tc := range cases {
		def := tableDef(tbl)
		def.Columns[5].Default, def.Columns[5].Nullable = tc.def, tc.nullable
		var want []string
		for _, w := range tc.want {
			want = append(want, `ALTER TABLE "SHOP"."RS_CUSTOMERS" `+w)
		}
		wantStatements(t, alterSQL(t, tbl, def), want)
	}
	def := tableDef(tbl)
	def.Columns[5].Nullable = true
	if _, err := testConn().AlterTableSQL(tbl, def); err == nil || !strings.Contains(err.Error(), "DEFAULT ON NULL") {
		t.Errorf("nullable ON NULL column: %v", err)
	}
	// Adopting ON NULL makes a nullable column NOT NULL by itself.
	def = tableDef(tbl)
	def.Columns[4].Default, def.Columns[4].Nullable = strp("ON NULL 0"), false
	wantStatements(t, alterSQL(t, tbl, def), []string{`ALTER TABLE "SHOP"."RS_CUSTOMERS" MODIFY ("BALANCE" DEFAULT ON NULL 0)`})
}

func TestAlterIdentity(t *testing.T) {
	tbl := describedCustomers()
	def := tableDef(tbl)
	def.Columns[0].Default = strp("GENERATED ALWAYS AS IDENTITY")
	wantStatements(t, alterSQL(t, tbl, def), []string{`ALTER TABLE "SHOP"."RS_CUSTOMERS" MODIFY ("ID" GENERATED ALWAYS AS IDENTITY)`})

	// Switching auto-increment off drops the identity, whatever the stale
	// clause in the default says; a new plain default follows.
	def = tableDef(tbl)
	def.Columns[0].AutoIncrement = false
	wantStatements(t, alterSQL(t, tbl, def), []string{`ALTER TABLE "SHOP"."RS_CUSTOMERS" MODIFY ("ID" DROP IDENTITY)`})
	def.Columns[0].Default = strp("0")
	wantStatements(t, alterSQL(t, tbl, def), []string{
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" MODIFY ("ID" DROP IDENTITY)`,
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" MODIFY ("ID" DEFAULT 0)`,
	})

	for _, set := range []func(*driver.ColumnDef){
		func(c *driver.ColumnDef) { c.AutoIncrement = true },
		func(c *driver.ColumnDef) { c.Default = strp("GENERATED ALWAYS AS IDENTITY") },
	} {
		def = tableDef(tbl)
		set(defColumn(&def, "BALANCE"))
		if _, err := testConn().AlterTableSQL(tbl, def); err == nil || err.Error() != "Oracle cannot make existing column BALANCE an identity column; add a new column instead" {
			t.Errorf("identity on existing column: %v", err)
		}
	}
	// New columns can be identities.
	o := describedOrders()
	def = tableDef(o)
	def.Columns = append(def.Columns, driver.ColumnDef{Column: driver.Column{Name: "SEQ", Type: "NUMBER", AutoIncrement: true, Nullable: true}})
	wantStatements(t, alterSQL(t, o, def), []string{`ALTER TABLE "SHOP"."RS_ORDERS" ADD ("SEQ" NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY)`})
}

