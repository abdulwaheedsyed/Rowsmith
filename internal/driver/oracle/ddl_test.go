func TestAlterConstraints(t *testing.T) {
	tbl := describedCustomers()
	def := tableDef(tbl)
	def.Checks = []driver.Check{{Name: "RS_CUSTOMERS_BALANCE_CK", Expression: "BALANCE >= -100"}, {Name: "RS_CUSTOMERS_NAME_CK", Expression: "NAME IS NOT NULL"}}
	def.Indexes = []driver.Index{
		{Name: "RS_CUSTOMERS_EMAIL_UK", Columns: []string{"EMAIL", "NAME"}, Unique: true},        // unique constraint widened
		{Name: "RS_CUSTOMERS_LOWER_IX", Columns: []string{`LOWER("EMAIL")`}, Desc: []bool{true}}, // now descending
		{Name: "RS_CUSTOMERS_BAL_BX", Columns: []string{"BALANCE"}, Type: "bitmap"},
	}
	wantStatements(t, alterSQL(t, tbl, def), []string{
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" DROP CONSTRAINT "RS_CUSTOMERS_BALANCE_CK"`,
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" DROP CONSTRAINT "SYS_C008431"`,
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" DROP CONSTRAINT "RS_CUSTOMERS_EMAIL_UK" DROP INDEX`,
		`DROP INDEX "SHOP"."RS_CUSTOMERS_LOWER_IX"`,
		`DROP INDEX "SHOP"."RS_CUSTOMERS_REV_IX"`,
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" ADD CONSTRAINT "RS_CUSTOMERS_EMAIL_UK" UNIQUE ("EMAIL", "NAME")`,
		`CREATE INDEX "SHOP"."RS_CUSTOMERS_LOWER_IX" ON "SHOP"."RS_CUSTOMERS" (LOWER("EMAIL") DESC)`,
		`CREATE BITMAP INDEX "SHOP"."RS_CUSTOMERS_BAL_BX" ON "SHOP"."RS_CUSTOMERS" ("BALANCE")`,
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" ADD CONSTRAINT "RS_CUSTOMERS_BALANCE_CK" CHECK (BALANCE >= -100)`,
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" ADD CONSTRAINT "RS_CUSTOMERS_NAME_CK" CHECK (NAME IS NOT NULL)`,
	})

	// Keys other tables reference cannot go.
	def = tableDef(tbl)
	def.PrimaryKey = []string{"ID", "EMAIL"}
	if _, err := testConn().AlterTableSQL(tbl, def); err == nil ||
		err.Error() != "the primary key is referenced by foreign key RS_ORDERS.RS_ORDERS_CUSTOMER_FK; drop that foreign key first" {
		t.Errorf("referenced primary key: %v", err)
	}

	// Primary key and foreign keys of a table nobody references.
	o := describedOrders()
	def = tableDef(o)
	def.PrimaryKey = []string{"ID", "REGION"}
	def.ForeignKeys[0].OnDelete = "SET NULL"
	def.ForeignKeys = append(def.ForeignKeys, driver.ForeignKey{Name: "RS_ORDERS_SELF_FK", Columns: []string{"TOTAL"}, RefTable: driver.ObjectRef{Schema: "SALES", Name: "TOTALS"}, RefColumns: []string{"AMOUNT"}})
	def.Indexes = def.Indexes[:1]
	wantStatements(t, alterSQL(t, o, def), []string{
		`ALTER TABLE "SHOP"."RS_ORDERS" DROP CONSTRAINT "RS_ORDERS_CUSTOMER_FK"`,
		`ALTER TABLE "SHOP"."RS_ORDERS" DROP PRIMARY KEY DROP INDEX`,
		`DROP INDEX "SHOP"."RS_ORDERS_REGION_BX"`,
		`ALTER TABLE "SHOP"."RS_ORDERS" ADD CONSTRAINT "RS_ORDERS_PK" PRIMARY KEY ("ID", "REGION")`,
		`ALTER TABLE "SHOP"."RS_ORDERS" ADD CONSTRAINT "RS_ORDERS_CUSTOMER_FK" FOREIGN KEY ("CUSTOMER_ID") REFERENCES "SHOP"."RS_CUSTOMERS" ("ID") ON DELETE SET NULL`,
		`ALTER TABLE "SHOP"."RS_ORDERS" ADD CONSTRAINT "RS_ORDERS_SELF_FK" FOREIGN KEY ("TOTAL") REFERENCES "SALES"."TOTALS" ("AMOUNT")`,
	})

	// A system-named primary key is replaced by TABLE_PK; removing it is enough.
	def = tableDef(tbl)
	def.PrimaryKey = nil
	tbl.Referenced = nil
	wantStatements(t, alterSQL(t, tbl, def), []string{`ALTER TABLE "SHOP"."RS_CUSTOMERS" DROP PRIMARY KEY DROP INDEX`})
	def.PrimaryKey = []string{"EMAIL"}
	def.Ref.Name = "RS_PEOPLE"
	wantStatements(t, alterSQL(t, tbl, def), []string{
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" DROP PRIMARY KEY DROP INDEX`,
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" ADD CONSTRAINT "RS_PEOPLE_PK" PRIMARY KEY ("EMAIL")`,
		`ALTER TABLE "SHOP"."RS_CUSTOMERS" RENAME TO "RS_PEOPLE"`,
	})

	for want, set := range map[string]func(*driver.TableDef){
		"Oracle foreign keys have no ON UPDATE rule": func(d *driver.TableDef) { d.ForeignKeys[0].OnUpdate = "CASCADE" },
		"not SET DEFAULT":    func(d *driver.TableDef) { d.ForeignKeys[0].OnDelete = "SET DEFAULT" },
		"no partial indexes": func(d *driver.TableDef) { d.Indexes[1].Where = "REGION IS NOT NULL" },
		"cannot be unique":   func(d *driver.TableDef) { d.Indexes[1].Unique = true },
	} {
		def := tableDef(o)
		set(&def)
		if _, err := testConn().AlterTableSQL(o, def); err == nil || !strings.Contains(err.Error(), want) {
			t.Errorf("want %q, got %v", want, err)
		}
	}
}

// Renaming a column carries its keys and indexes along in Oracle, whether
// the editor renames them in the definition or keeps the old name.
func TestAlterRenameKeepsKeys(t *testing.T) {
	o := describedOrders()
	o.Indexes = append(o.Indexes, driver.Index{Name: "RS_ORDERS_CUST_IX", Columns: []string{"CUSTOMER_ID", "ID"}, Type: "btree", Desc: []bool{false, true}})
	for _, follow := range []bool{false, true} {
		def := tableDef(o)
		def.Columns[0].Name, def.Columns[1].Name = "ORDER_ID", "CLIENT_ID"
		if follow {
			def.PrimaryKey = []string{"ORDER_ID"}
			def.ForeignKeys[0].Columns = []string{"CLIENT_ID"}
			def.Indexes[2].Columns = []string{"CLIENT_ID", "ORDER_ID"}
		}
		wantStatements(t, alterSQL(t, o, def), []string{
			`ALTER TABLE "SHOP"."RS_ORDERS" RENAME COLUMN "ID" TO "ORDER_ID"`,
			`ALTER TABLE "SHOP"."RS_ORDERS" RENAME COLUMN "CUSTOMER_ID" TO "CLIENT_ID"`,
		})
	}
	// Swapping two names is still a change of the index.
	def := tableDef(o)
	def.Indexes[2].Columns = []string{"ID", "CUSTOMER_ID"}
	stmts := alterSQL(t, o, def)
	if len(stmts) != 2 || !strings.HasPrefix(stmts[1], `CREATE INDEX "SHOP"."RS_ORDERS_CUST_IX" ON "SHOP"."RS_ORDERS" ("ID", "CUSTOMER_ID" DESC)`) {
		t.Errorf("changed index:\n%s", strings.Join(stmts, "\n"))
	}
}

