func TestDropTruncateRename(t *testing.T) {
	c := testConn()
	ref := func(kind, name string) driver.ObjectRef {
		return driver.ObjectRef{Schema: "SHOP", Name: name, Kind: kind}
	}
	drops := []struct {
		ref     driver.ObjectRef
		cascade bool
		want    string
	}{
		{ref("table", "T"), false, `DROP TABLE "SHOP"."T"`},
		{ref("table", "T"), true, `DROP TABLE "SHOP"."T" CASCADE CONSTRAINTS`},
		{ref("view", "V"), true, `DROP VIEW "SHOP"."V" CASCADE CONSTRAINTS`},
		{ref("materialized_view", "MV"), true, `DROP MATERIALIZED VIEW "SHOP"."MV"`},
		{ref("sequence", "S"), false, `DROP SEQUENCE "SHOP"."S"`},
		{ref("synonym", "S"), false, `DROP SYNONYM "SHOP"."S"`},
		{ref("package", "P"), false, `DROP PACKAGE "SHOP"."P"`},
		{ref("package_body", "P"), false, `DROP PACKAGE BODY "SHOP"."P"`},
		{ref("procedure", "P"), false, `DROP PROCEDURE "SHOP"."P"`},
		{ref("function", "F"), false, `DROP FUNCTION "SHOP"."F"`},
		{ref("trigger", "TR"), false, `DROP TRIGGER "SHOP"."TR"`},
		{ref("type", "TY"), true, `DROP TYPE "SHOP"."TY" FORCE`},
		{ref("index", "IX"), false, `DROP INDEX "SHOP"."IX"`},
		{driver.ObjectRef{Name: "T", Kind: "table"}, false, `DROP TABLE "SHOP"."T"`},
	}
	for _, d := range drops {
		got, err := c.DropObjectSQL(d.ref, d.cascade)
		if err != nil || len(got) != 1 || got[0] != d.want {
			t.Errorf("drop %+v: %q %v", d.ref, got, err)
		}
	}
	if _, err := c.DropObjectSQL(ref("database", "X"), false); err == nil {
		t.Error("unknown kind accepted")
	}
	if got, err := c.TruncateSQL(ref("table", "T")); err != nil || got[0] != `TRUNCATE TABLE "SHOP"."T"` {
		t.Errorf("truncate %q %v", got, err)
	}
	if _, err := c.TruncateSQL(ref("view", "V")); err == nil {
		t.Error("truncating a view accepted")
	}

	renames := map[driver.ObjectRef]string{
		ref("table", "T"):             `ALTER TABLE "SHOP"."T" RENAME TO "N"`,
		{Schema: "HR", Name: "T"}:     `ALTER TABLE "HR"."T" RENAME TO "N"`,
		ref("index", "IX"):            `ALTER INDEX "SHOP"."IX" RENAME TO "N"`,
		ref("trigger", "TR"):          `ALTER TRIGGER "SHOP"."TR" RENAME TO "N"`,
		ref("view", "V"):              `RENAME "V" TO "N"`,
		{Name: "S", Kind: "sequence"}: `RENAME "S" TO "N"`,
		ref("synonym", "SY"):          `RENAME "SY" TO "N"`,
	}
	for r, want := range renames {
		if got, err := c.RenameObjectSQL(r, "N"); err != nil || len(got) != 1 || got[0] != want {
			t.Errorf("rename %+v: %q %v", r, got, err)
		}
	}
	for r, want := range map[driver.ObjectRef]string{
		{Schema: "HR", Name: "V", Kind: "view"}: "Oracle can only rename a view in your own schema (SHOP)",
		ref("procedure", "P"):                   "Oracle cannot rename a procedure; recreate it under the new name",
		ref("materialized_view", "MV"):          "Oracle cannot rename a materialized view; recreate it under the new name",
	} {
		if _, err := c.RenameObjectSQL(r, "N"); err == nil || err.Error() != want {
			t.Errorf("rename %+v: %v", r, err)
		}
	}
	if _, err := c.RenameObjectSQL(ref("table", "T"), " "); err == nil {
		t.Error("empty name accepted")
	}
	if _, err := c.CreateDatabaseSQL("X", nil); err == nil || !strings.Contains(err.Error(), "pluggable databases") {
		t.Errorf("create database: %v", err)
	}
	if _, err := c.DropDatabaseSQL("X"); err == nil {
		t.Error("drop database accepted")
	}
}

