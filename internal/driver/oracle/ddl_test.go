func alterSQL(t *testing.T, from *driver.Table, to driver.TableDef) []string {
	t.Helper()
	stmts, err := testConn().AlterTableSQL(from, to)
	if err != nil {
		t.Fatal(err)
	}
	return stmts
}

func wantStatements(t *testing.T, got, want []string) {
	t.Helper()
	if strings.Join(got, "\n") != strings.Join(want, "\n") {
		t.Errorf("statements\n got:\n%s\nwant:\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}
}

func defColumn(def *driver.TableDef, name string) *driver.ColumnDef {
	for i := range def.Columns {
		if def.Columns[i].OriginalName == name {
			return &def.Columns[i]
		}
	}
	panic("no column " + name)
}

func TestCreateTableSQL(t *testing.T) {
	stmts, err := testConn().CreateTableSQL(driver.TableDef{
		Ref: driver.ObjectRef{Name: "NOTES"},
		Columns: []driver.ColumnDef{
			{Column: driver.Column{Name: "ID", Type: "NUMBER(19)", AutoIncrement: true}},
			{Column: driver.Column{Name: "BODY", Type: "CLOB", Nullable: true, Comment: "it's free text"}},
			{Column: driver.Column{Name: "CREATED", Type: "TIMESTAMP", Default: strp("SYSTIMESTAMP")}},
			{Column: driver.Column{Name: "RANK", Type: "NUMBER", Default: strp("ON NULL 0")}},
			{Column: driver.Column{Name: "AUTHOR_ID", Type: "NUMBER(10)", Nullable: true, Default: strp("")}},
			{Column: driver.Column{Name: "Title", Type: "VARCHAR2(100 CHAR)", Nullable: true}},
			{Column: driver.Column{Name: "TITLE_UPPER", Generated: `UPPER("Title")`, Nullable: true}},
		},
		PrimaryKey:  []string{"ID"},
		Checks:      []driver.Check{{Name: "NOTES_RANK_CK", Expression: "RANK >= 0"}, {Expression: "LENGTH(BODY) > 0"}},
		ForeignKeys: []driver.ForeignKey{{Name: "NOTES_AUTHOR_FK", Columns: []string{"AUTHOR_ID"}, RefTable: driver.ObjectRef{Name: "AUTHORS"}, RefColumns: []string{"ID"}, OnDelete: "SET NULL"}},
		Indexes: []driver.Index{
			{Name: "NOTES_CREATED_IX", Columns: []string{"CREATED", "Title"}, Desc: []bool{true}},
			{Name: "NOTES_TITLE_UK", Columns: []string{"(LOWER(\"Title\"))"}, Unique: true},
			{Name: "NOTES_RANK_BX", Columns: []string{"RANK"}, Type: "bitmap"},
		},
		Comment: "Team notes",
	})
	if err != nil {
		t.Fatal(err)
	}
	wantStatements(t, stmts, []string{
		`CREATE TABLE "SHOP"."NOTES" (
  "ID" NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
  "BODY" CLOB,
  "CREATED" TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  "RANK" NUMBER DEFAULT ON NULL 0 NOT NULL,
  "AUTHOR_ID" NUMBER(10),
  "Title" VARCHAR2(100 CHAR),
  "TITLE_UPPER" GENERATED ALWAYS AS (UPPER("Title")) VIRTUAL,
  CONSTRAINT "NOTES_PK" PRIMARY KEY ("ID"),
  CONSTRAINT "NOTES_RANK_CK" CHECK (RANK >= 0),
  CHECK (LENGTH(BODY) > 0),
  CONSTRAINT "NOTES_AUTHOR_FK" FOREIGN KEY ("AUTHOR_ID") REFERENCES "SHOP"."AUTHORS" ("ID") ON DELETE SET NULL
)`,
		`CREATE INDEX "SHOP"."NOTES_CREATED_IX" ON "SHOP"."NOTES" ("CREATED" DESC, "Title")`,
		`CREATE UNIQUE INDEX "SHOP"."NOTES_TITLE_UK" ON "SHOP"."NOTES" ((LOWER("Title")))`,
		`CREATE BITMAP INDEX "SHOP"."NOTES_RANK_BX" ON "SHOP"."NOTES" ("RANK")`,
		`COMMENT ON TABLE "SHOP"."NOTES" IS 'Team notes'`,
		`COMMENT ON COLUMN "SHOP"."NOTES"."BODY" IS 'it''s free text'`,
	})

	// A primary key name that does not fit falls back to a system name.
	c := testConn()
	c.version = "12.1.0.2.0"
	stmts, err = c.CreateTableSQL(driver.TableDef{Ref: driver.ObjectRef{Schema: "HR", Name: strings.Repeat("T", 28)},
		Columns: []driver.ColumnDef{{Column: driver.Column{Name: "ID", Type: "NUMBER"}}}, PrimaryKey: []string{"ID"}})
	if err != nil || !strings.Contains(stmts[0], "\n  PRIMARY KEY (\"ID\")\n") || !strings.HasPrefix(stmts[0], `CREATE TABLE "HR"."TTTT`) {
		t.Errorf("long name: %v %q", err, stmts)
	}
}

func TestCreateTableErrors(t *testing.T) {
	cols := func(cs ...driver.Column) []driver.ColumnDef {
		out := make([]driver.ColumnDef, len(cs))
		for i, c := range cs {
			out[i].Column = c
		}
		return out
	}
	a := driver.Column{Name: "A", Type: "NUMBER"}
	table := func(def driver.TableDef) driver.TableDef {
		def.Ref.Name = "T"
		if def.Columns == nil {
			def.Columns = cols(a)
		}
		return def
	}
	fk := driver.ForeignKey{Name: "FK", Columns: []string{"A"}, RefTable: driver.ObjectRef{Name: "P"}, RefColumns: []string{"ID"}}
	onUpdate, setDefault := fk, fk
	onUpdate.OnUpdate, setDefault.OnDelete = "CASCADE", "SET DEFAULT"
	cases := map[string]driver.TableDef{
		"give the table a name":                                      {Columns: cols(a)},
		"a table needs at least one column":                          {Ref: driver.ObjectRef{Name: "T"}},
		"column A needs a type":                                      table(driver.TableDef{Columns: cols(driver.Column{Name: "A"})}),
		"always virtual":                                             table(driver.TableDef{Columns: cols(driver.Column{Name: "A", Generated: "1", GeneratedStored: true})}),
		"column A is listed twice":                                   table(driver.TableDef{Columns: cols(a, a)}),
		"foreign key FK: Oracle foreign keys have no ON UPDATE rule": table(driver.TableDef{ForeignKeys: []driver.ForeignKey{onUpdate}}),
		"CASCADE or SET NULL only, not SET DEFAULT":                  table(driver.TableDef{ForeignKeys: []driver.ForeignKey{setDefault}}),
		"index IX: Oracle has no partial indexes":                    table(driver.TableDef{Indexes: []driver.Index{{Name: "IX", Columns: []string{"A"}, Where: "A > 0"}}}),
		"a bitmap index cannot be unique":                            table(driver.TableDef{Indexes: []driver.Index{{Name: "IX", Columns: []string{"A"}, Unique: true, Type: "bitmap"}}}),
		"every index needs a name":                                   table(driver.TableDef{Indexes: []driver.Index{{Columns: []string{"A"}}}}),
		"index IX is a domain index":                                 table(driver.TableDef{Indexes: []driver.Index{{Name: "IX", Columns: []string{"A"}, Type: "domain"}}}),
	}
	for want, def := range cases {
		if _, err := testConn().CreateTableSQL(def); err == nil || !strings.Contains(err.Error(), want) {
			t.Errorf("want error %q, got %v", want, err)
		}
	}
}

func TestAlterUnchanged(t *testing.T) {
	for _, tbl := range []*driver.Table{describedCustomers(), describedOrders(), ddlTableOnly()} {
		if stmts := alterSQL(t, tbl, tableDef(tbl)); len(stmts) != 0 {
			t.Errorf("%s: unchanged definition produced:\n%s", tbl.Ref.Name, strings.Join(stmts, "\n"))
		}
	}
	// The editor may leave out what Describe reports only for display.
	tbl := describedCustomers()
	def := tableDef(tbl)
	for i := range def.Indexes {
		def.Indexes[i].Definition = ""
		if def.Indexes[i].Type == "btree" {
			def.Indexes[i].Type, def.Indexes[i].Desc = "", nil
		}
	}
	def.Indexes = def.Indexes[1:] // primary entries are ignored
	def.Ref.Kind, def.Options = "", nil
	def.Columns[0].Default = nil // identity without its clause
	def.Columns[2].Type = "varchar2(200  byte)"
	for i := range def.ForeignKeys {
		def.ForeignKeys[i].RefTable.Schema = ""
	}
	if stmts := alterSQL(t, tbl, def); len(stmts) != 0 {
		t.Errorf("equivalent definition produced:\n%s", strings.Join(stmts, "\n"))
	}
	orders := describedOrders()
	def = tableDef(orders)
	def.ForeignKeys[0].RefTable.Schema, def.ForeignKeys[0].OnDelete, def.ForeignKeys[0].Table = "", "cascade", nil
	if stmts := alterSQL(t, orders, def); len(stmts) != 0 {
		t.Errorf("equivalent foreign key produced:\n%s", strings.Join(stmts, "\n"))
	}
}

