func strp(s string) *string { return &s }

// tableDef builds the definition the structure editor submits for an
// unchanged table: Describe's result as JSON, every column linked by name.
func tableDef(t *driver.Table) driver.TableDef {
	var cp driver.Table
	b, _ := json.Marshal(t)
	_ = json.Unmarshal(b, &cp)
	def := driver.TableDef{Ref: cp.Ref, PrimaryKey: cp.PrimaryKey, Indexes: cp.Indexes, ForeignKeys: cp.ForeignKeys, Checks: cp.Checks,
		Comment: cp.Comment, Options: cp.Options}
	for _, col := range cp.Columns {
		def.Columns = append(def.Columns, driver.ColumnDef{Column: col, OriginalName: col.Name})
	}
	return def
}

// describedCustomers is RS_CUSTOMERS as describe.go reports it, with the
// artefacts a round trip must survive: a system-named primary key, a unique
// constraint shown as its index, an identity column, a virtual column and
// a function-based index.
func describedCustomers() *driver.Table {
	ident := "GENERATED BY DEFAULT AS IDENTITY"
	tbl := &driver.Table{
		Ref: driver.ObjectRef{Schema: "SHOP", Name: "RS_CUSTOMERS", Kind: "table"}, Kind: "table", Comment: "Customers",
		Options: map[string]string{"tablespace": "USERS"},
		Columns: []driver.Column{
			{Name: "ID", Type: "NUMBER(10)", BaseType: "number", Kind: driver.KindInt, Default: &ident, AutoIncrement: true, PrimaryKey: true},
			{Name: "NAME", Type: "VARCHAR2(100 CHAR)", BaseType: "varchar2", Kind: driver.KindString},
			{Name: "EMAIL", Type: "VARCHAR2(200 BYTE)", BaseType: "varchar2", Kind: driver.KindString, Nullable: true, Comment: "Login email"},
			{Name: "CREATED", Type: "DATE", BaseType: "date", Kind: driver.KindDateTime, Nullable: true, Default: strp("SYSDATE")},
			{Name: "BALANCE", Type: "NUMBER(12,2)", BaseType: "number", Kind: driver.KindDecimal, Nullable: true, Default: strp("0")},
			{Name: "STATUS", Type: "VARCHAR2(10 BYTE)", BaseType: "varchar2", Kind: driver.KindString, Default: strp("ON NULL 'new'")},
			{Name: "NAME_UPPER", Type: "VARCHAR2(400 CHAR)", BaseType: "varchar2", Kind: driver.KindString, Nullable: true, Generated: `UPPER("NAME")`},
		},
		PrimaryKey: []string{"ID"},
		Checks:     []driver.Check{{Name: "RS_CUSTOMERS_BALANCE_CK", Expression: "BALANCE >= 0"}, {Name: "SYS_C008431", Expression: "NAME <> 'x'"}},
		Referenced: []driver.ForeignKey{{Name: "RS_ORDERS_CUSTOMER_FK", Columns: []string{"CUSTOMER_ID"}, RefColumns: []string{"ID"}, OnDelete: "CASCADE",
			RefTable: driver.ObjectRef{Schema: "SHOP", Name: "RS_CUSTOMERS", Kind: "table"}, Table: &driver.ObjectRef{Schema: "SHOP", Name: "RS_ORDERS", Kind: "table"}}},
		Indexes: []driver.Index{
			{Name: "SYS_C008430", Columns: []string{"ID"}, Unique: true, Primary: true, Type: "btree", Desc: []bool{false}},
			{Name: "RS_CUSTOMERS_EMAIL_UK", Columns: []string{"EMAIL"}, Unique: true, Type: "btree", Desc: []bool{false}},
			{Name: "RS_CUSTOMERS_LOWER_IX", Columns: []string{`LOWER("EMAIL")`}, Type: "btree", Desc: []bool{false}},
			{Name: "RS_CUSTOMERS_REV_IX", Columns: []string{"CREATED", "BALANCE"}, Type: "btree (reverse)", Desc: []bool{false, true}},
		},
		RowKey: []string{"ID"}, RowKeyKind: "primary", Editable: true,
	}
	cols := map[string]bool{}
	for _, c := range tbl.Columns {
		cols[c.Name] = true
	}
	for i := range tbl.Indexes {
		tbl.Indexes[i].Definition = indexDDL("SHOP", tbl.Indexes[i], tbl, cols)
	}
	tbl.Indexes[0].Definition = constraintDDL(tbl, "SYS_C008430", "PRIMARY KEY", []string{"ID"})
	tbl.Indexes[1].Definition = constraintDDL(tbl, "RS_CUSTOMERS_EMAIL_UK", "UNIQUE", []string{"EMAIL"})
	return tbl
}

