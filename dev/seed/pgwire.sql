-- Sample "shop" database for PostgreSQL-compatible servers (CockroachDB,
-- YugabyteDB): syntax both accept, run in the shop database.
CREATE TYPE tier AS ENUM ('free', 'pro', 'enterprise');

CREATE TABLE categories (
  id INT8 PRIMARY KEY,
  name VARCHAR(80) NOT NULL UNIQUE,
  parent_id INT8 REFERENCES categories (id) ON DELETE SET NULL
);
COMMENT ON TABLE categories IS 'Product taxonomy';

CREATE TABLE customers (
  id INT8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(190) NOT NULL UNIQUE,
  full_name VARCHAR(120) NOT NULL,
  tier tier NOT NULL DEFAULT 'free',
  country CHAR(2) NOT NULL DEFAULT 'US',
  is_active BOOL NOT NULL DEFAULT true,
  preferences JSONB,
  tags TEXT[],
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
COMMENT ON TABLE customers IS 'People who buy things';
COMMENT ON COLUMN customers.tier IS 'Billing plan';
CREATE INDEX idx_customers_country ON customers (country, tier);

CREATE TABLE products (
  id INT8 PRIMARY KEY,
  sku VARCHAR(32) NOT NULL UNIQUE,
  name VARCHAR(160) NOT NULL,
  category_id INT8 NOT NULL REFERENCES categories (id),
  price NUMERIC(10,2) NOT NULL,
  cost NUMERIC(10,2) NOT NULL,
  margin NUMERIC(10,2) GENERATED ALWAYS AS (price - cost) STORED,
  stock INT4 NOT NULL DEFAULT 0 CHECK (stock >= 0),
  weight_kg FLOAT8,
  description TEXT,
  thumbnail BYTEA
);
CREATE INDEX idx_products_category ON products (category_id);
CREATE INDEX idx_products_low_stock ON products (stock) WHERE stock < 10;

CREATE TABLE orders (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  number INT8 NOT NULL UNIQUE,
  customer_id INT8 NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
  status VARCHAR(12) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'paid', 'shipped', 'delivered', 'refunded')),
  total NUMERIC(12,2) NOT NULL DEFAULT 0,
  placed_at TIMESTAMPTZ NOT NULL,
  ship_window INTERVAL,
  client_ip INET,
  notes TEXT
);
CREATE INDEX idx_orders_customer ON orders (customer_id, placed_at);

CREATE TABLE audit_events (
  happened_at TIMESTAMPTZ NOT NULL,
  actor VARCHAR(80) NOT NULL,
  action VARCHAR(40) NOT NULL,
  payload JSONB
);

